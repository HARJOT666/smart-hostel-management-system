-- Smart Hostel Management System
-- 01_core_schema.sql : the 8 core tables from Review 1
-- Primary keys, NOT NULL and DEFAULT are defined here.
-- Foreign keys, UNIQUE and CHECK constraints are added in 02_core_constraints.sql
-- =====================================================================

-- Hostel blocks
CREATE TABLE hostel (
    hostel_id      NUMBER(4)     GENERATED BY DEFAULT AS IDENTITY,
    hostel_name    VARCHAR2(60)  NOT NULL,
    gender_type    VARCHAR2(6)   NOT NULL,
    location       VARCHAR2(100) NOT NULL,
    total_floors   NUMBER(2),
    CONSTRAINT pk_hostel PRIMARY KEY (hostel_id)
);

-- Hostel residents (also used for student login)
CREATE TABLE student (
    student_id       NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY,
    registration_no  VARCHAR2(15)  NOT NULL,
    name             VARCHAR2(100) NOT NULL,
    email            VARCHAR2(100) NOT NULL,
    phone            VARCHAR2(15)  NOT NULL,
    gender           VARCHAR2(6)   NOT NULL,
    year             NUMBER(1),
    branch           VARCHAR2(60)  NOT NULL,
    cgpa             NUMBER(4,2),
    password_hash    VARCHAR2(100) NOT NULL,      -- refinement: BCrypt hash for login
    CONSTRAINT pk_student PRIMARY KEY (student_id)
);

-- Rooms inside a hostel
CREATE TABLE room (
    room_id         NUMBER(6)    GENERATED BY DEFAULT AS IDENTITY,
    room_number     VARCHAR2(10) NOT NULL,
    floor_no        NUMBER(2),
    room_type       VARCHAR2(10),
    capacity        NUMBER(1)    NOT NULL,
    occupied_count  NUMBER(1)    DEFAULT 0 NOT NULL,   -- maintained by trigger
    hostel_id       NUMBER(4)    NOT NULL,
    CONSTRAINT pk_room PRIMARY KEY (room_id)
);

-- Admins, wardens and maintenance staff (also used for staff login)
CREATE TABLE staff (
    staff_id        NUMBER(5)     GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR2(100) NOT NULL,
    role            VARCHAR2(12)  NOT NULL,
    specialization  VARCHAR2(15),
    phone           VARCHAR2(15)  NOT NULL,
    email           VARCHAR2(100) NOT NULL,       -- used as the login username
    hostel_id       NUMBER(4)     NOT NULL,
    password_hash   VARCHAR2(100) NOT NULL,       -- refinement: BCrypt hash for login
    CONSTRAINT pk_staff PRIMARY KEY (staff_id)
);

-- Which bed of which room is allotted to which student (associative entity)
CREATE TABLE room_allocation (
    allocation_id    NUMBER(8)   GENERATED BY DEFAULT AS IDENTITY,
    student_id       NUMBER(6)   NOT NULL,
    room_id          NUMBER(6)   NOT NULL,
    allocated_by     NUMBER(5)   NOT NULL,
    bed_number       NUMBER(1)   NOT NULL,
    allocation_date  DATE        DEFAULT SYSDATE NOT NULL,
    vacate_date      DATE,
    status           VARCHAR2(10) DEFAULT 'Active' NOT NULL,
    CONSTRAINT pk_room_allocation PRIMARY KEY (allocation_id)
);

-- Maintenance complaints
CREATE TABLE complaint (
    complaint_id           NUMBER(8)      GENERATED BY DEFAULT AS IDENTITY,
    student_id             NUMBER(6)      NOT NULL,
    assigned_to            NUMBER(5),                       -- NULL until assigned
    category               VARCHAR2(15)   NOT NULL,
    description            VARCHAR2(1000) NOT NULL,
    priority               VARCHAR2(6)    DEFAULT 'Medium' NOT NULL,
    status                 VARCHAR2(12)   DEFAULT 'Open' NOT NULL,
    created_date           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_date          TIMESTAMP,
    remarks                VARCHAR2(500),
    scheduled_date         DATE,                            -- refinement: maintenance schedule
    image_path             VARCHAR2(255),                   -- refinement: photo by student
    completion_image_path  VARCHAR2(255),                   -- refinement: proof of work
    CONSTRAINT pk_complaint PRIMARY KEY (complaint_id)
);

-- Leave applications
CREATE TABLE leave_request (
    leave_id      NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    student_id    NUMBER(6)     NOT NULL,
    approved_by   NUMBER(5),                                -- NULL while pending
    start_date    DATE          NOT NULL,
    end_date      DATE          NOT NULL,
    reason        VARCHAR2(300) NOT NULL,
    destination   VARCHAR2(100),
    applied_date  DATE          DEFAULT SYSDATE NOT NULL,
    status        VARCHAR2(10)  DEFAULT 'Pending' NOT NULL,
    CONSTRAINT pk_leave_request PRIMARY KEY (leave_id)
);

-- Visitor entry passes
CREATE TABLE visitor_pass (
    pass_id              NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    student_id           NUMBER(6)     NOT NULL,
    approved_by          NUMBER(5),                         -- NULL while pending
    visitor_name         VARCHAR2(100) NOT NULL,
    visitor_phone        VARCHAR2(15)  NOT NULL,
    relation_to_student  VARCHAR2(30),
    purpose              VARCHAR2(200),
    visit_date           DATE          NOT NULL,
    entry_time           TIMESTAMP,
    exit_time            TIMESTAMP,
    qr_code              VARCHAR2(40),                      -- generated by trigger on approval
    status               VARCHAR2(10)  DEFAULT 'Pending' NOT NULL,
    CONSTRAINT pk_visitor_pass PRIMARY KEY (pass_id)
);
