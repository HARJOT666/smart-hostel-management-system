-- =====================================================================
-- 03_extension_tables.sql : application extension tables (SE modules)
--
-- These six tables support Software Engineering features
-- (FR-06 fees, FR-07 announcements, FR-08 marketplace, FR-09 inventory,
--  lost & found, mess menu). They are NOT part of the 8-table core
-- DBMS design from Review 1. Each one only references a core table
-- through a foreign key, so the core relations are unchanged.
-- =====================================================================

-- FR-06: fee dues and payments (one row per fee item per semester).
-- Payment status is NOT stored; it is derived from amount_paid vs amount_due
-- (storing it would create a transitive dependency).
CREATE TABLE fee_payment (
    payment_id       NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    student_id       NUMBER(6)     NOT NULL,
    semester         VARCHAR2(20)  NOT NULL,
    fee_type         VARCHAR2(20)  NOT NULL,
    amount_due       NUMBER(10,2)  NOT NULL,
    amount_paid      NUMBER(10,2)  DEFAULT 0 NOT NULL,
    due_date         DATE          NOT NULL,
    paid_date        DATE,
    payment_mode     VARCHAR2(10),
    transaction_ref  VARCHAR2(30),
    CONSTRAINT pk_fee_payment     PRIMARY KEY (payment_id),
    CONSTRAINT fk_fee_student     FOREIGN KEY (student_id) REFERENCES student (student_id),
    CONSTRAINT uq_fee_item        UNIQUE (student_id, semester, fee_type),
    CONSTRAINT uq_fee_txn         UNIQUE (transaction_ref),
    CONSTRAINT ck_fee_type        CHECK (fee_type IN ('Hostel Rent', 'Mess', 'Caution Deposit')),
    CONSTRAINT ck_fee_amounts     CHECK (amount_due > 0 AND amount_paid BETWEEN 0 AND amount_due),
    CONSTRAINT ck_fee_mode        CHECK (payment_mode IN ('Online', 'Card', 'Cash', 'DD'))
);

-- FR-07: notice board. hostel_id NULL means the notice is for all hostels.
CREATE TABLE announcement (
    announcement_id  NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
    title            VARCHAR2(150)  NOT NULL,
    body             VARCHAR2(2000) NOT NULL,
    category         VARCHAR2(12)   DEFAULT 'General' NOT NULL,
    posted_by        NUMBER(5)      NOT NULL,
    hostel_id        NUMBER(4),
    posted_date      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    expiry_date      DATE,
    is_pinned        CHAR(1)        DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_announcement      PRIMARY KEY (announcement_id),
    CONSTRAINT fk_announce_staff    FOREIGN KEY (posted_by) REFERENCES staff (staff_id),
    CONSTRAINT fk_announce_hostel   FOREIGN KEY (hostel_id) REFERENCES hostel (hostel_id),
    CONSTRAINT ck_announce_category CHECK (category IN ('General', 'Maintenance', 'Mess', 'Event', 'Urgent')),
    CONSTRAINT ck_announce_pinned   CHECK (is_pinned IN ('Y', 'N'))
);

-- FR-08: student marketplace (buy / sell hostel essentials)
CREATE TABLE marketplace_listing (
    listing_id       NUMBER(6)      GENERATED BY DEFAULT AS IDENTITY,
    seller_id        NUMBER(6)      NOT NULL,
    buyer_id         NUMBER(6),
    title            VARCHAR2(100)  NOT NULL,
    description      VARCHAR2(1000),
    category         VARCHAR2(12)   NOT NULL,
    price            NUMBER(8,2)    NOT NULL,
    item_condition   VARCHAR2(10)   NOT NULL,
    status           VARCHAR2(10)   DEFAULT 'Available' NOT NULL,
    image_path       VARCHAR2(255),
    listed_date      DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_marketplace_listing PRIMARY KEY (listing_id),
    CONSTRAINT fk_listing_seller      FOREIGN KEY (seller_id) REFERENCES student (student_id),
    CONSTRAINT fk_listing_buyer       FOREIGN KEY (buyer_id)  REFERENCES student (student_id),
    CONSTRAINT ck_listing_category    CHECK (category IN ('Books', 'Electronics', 'Cycle', 'Furniture', 'Bedding', 'Other')),
    CONSTRAINT ck_listing_price       CHECK (price >= 0),
    CONSTRAINT ck_listing_condition   CHECK (item_condition IN ('New', 'Like New', 'Good', 'Fair')),
    CONSTRAINT ck_listing_status      CHECK (status IN ('Available', 'Sold', 'Withdrawn')),
    CONSTRAINT ck_listing_buyer       CHECK (buyer_id IS NULL OR buyer_id <> seller_id)
);

-- FR-09: hostel inventory (one row per item type per hostel)
CREATE TABLE inventory_item (
    item_id           NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY,
    hostel_id         NUMBER(4)     NOT NULL,
    item_name         VARCHAR2(60)  NOT NULL,
    category          VARCHAR2(12)  NOT NULL,
    quantity_total    NUMBER(5)     DEFAULT 0 NOT NULL,
    quantity_damaged  NUMBER(5)     DEFAULT 0 NOT NULL,
    last_checked      DATE,
    CONSTRAINT pk_inventory_item   PRIMARY KEY (item_id),
    CONSTRAINT fk_inventory_hostel FOREIGN KEY (hostel_id) REFERENCES hostel (hostel_id),
    CONSTRAINT uq_inventory_item   UNIQUE (hostel_id, item_name),
    CONSTRAINT ck_inventory_cat    CHECK (category IN ('Furniture', 'Electrical', 'Appliance', 'Bedding', 'Cleaning', 'Other')),
    CONSTRAINT ck_inventory_qty    CHECK (quantity_total >= 0 AND quantity_damaged BETWEEN 0 AND quantity_total)
);

-- Lost and found portal
CREATE TABLE lost_found_item (
    item_id      NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY,
    reported_by  NUMBER(6)     NOT NULL,
    claimed_by   NUMBER(6),
    report_type  VARCHAR2(5)   NOT NULL,
    item_name    VARCHAR2(80)  NOT NULL,
    description  VARCHAR2(500),
    location     VARCHAR2(100),
    report_date  DATE          DEFAULT SYSDATE NOT NULL,
    status       VARCHAR2(8)   DEFAULT 'Open' NOT NULL,
    image_path   VARCHAR2(255),
    CONSTRAINT pk_lost_found_item  PRIMARY KEY (item_id),
    CONSTRAINT fk_lostfound_rep    FOREIGN KEY (reported_by) REFERENCES student (student_id),
    CONSTRAINT fk_lostfound_claim  FOREIGN KEY (claimed_by)  REFERENCES student (student_id),
    CONSTRAINT ck_lostfound_type   CHECK (report_type IN ('Lost', 'Found')),
    CONSTRAINT ck_lostfound_status CHECK (status IN ('Open', 'Claimed', 'Closed'))
);

-- Weekly mess menu of each hostel (one row per hostel, day and meal)
CREATE TABLE mess_menu (
    menu_id      NUMBER(5)     GENERATED BY DEFAULT AS IDENTITY,
    hostel_id    NUMBER(4)     NOT NULL,
    day_of_week  VARCHAR2(3)   NOT NULL,
    meal_type    VARCHAR2(10)  NOT NULL,
    menu_items   VARCHAR2(300) NOT NULL,
    CONSTRAINT pk_mess_menu    PRIMARY KEY (menu_id),
    CONSTRAINT fk_menu_hostel  FOREIGN KEY (hostel_id) REFERENCES hostel (hostel_id),
    CONSTRAINT uq_menu_slot    UNIQUE (hostel_id, day_of_week, meal_type),
    CONSTRAINT ck_menu_day     CHECK (day_of_week IN ('MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN')),
    CONSTRAINT ck_menu_meal    CHECK (meal_type IN ('Breakfast', 'Lunch', 'Snacks', 'Dinner'))
);

CREATE INDEX ix_fee_student      ON fee_payment (student_id);
CREATE INDEX ix_listing_seller   ON marketplace_listing (seller_id);
CREATE INDEX ix_listing_status   ON marketplace_listing (status);
CREATE INDEX ix_announce_hostel  ON announcement (hostel_id);
CREATE INDEX ix_lostfound_status ON lost_found_item (status);
