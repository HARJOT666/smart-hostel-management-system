package com.smarthostel.model;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import java.time.LocalDate;
import java.time.LocalDateTime;

@Entity
@Table(name = "visitor_pass")
@Getter
@Setter
@NoArgsConstructor
public class VisitorPass {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "pass_id")
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "student_id")
    private Student student;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "approved_by")
    private Staff approvedBy;

    @Column(name = "visitor_name", nullable = false)
    private String visitorName;

    @Column(name = "visitor_phone", nullable = false)
    private String visitorPhone;

    @Column(name = "relation_to_student")
    private String relationToStudent;

    private String purpose;

    @Column(name = "visit_date", nullable = false)
    private LocalDate visitDate;

    @Column(name = "entry_time")
    private LocalDateTime entryTime;

    @Column(name = "exit_time")
    private LocalDateTime exitTime;

    // Generated by the Oracle trigger trg_visitor_pass_qr when the pass is approved.
    @Generated(event = {EventType.INSERT, EventType.UPDATE})
    @Column(name = "qr_code", insertable = false, updatable = false)
    private String qrCode;

    /** Pending, Approved, Rejected, Completed */
    @Column(nullable = false)
    private String status = "Pending";
}
